"""Render results/*.json into results/REPORT.md (pure function of the JSON inputs)."""

from __future__ import annotations

import statistics
from pathlib import Path

from .util import RESULTS_DIR, load_json

HEADLINE_MODEL = "claude-sonnet-5-5"
SYMBOL = {"block": "BLOCK", "ask": "ask", "advise": "advise", "allow": "allow", "error": "error",
          "no_hook": "·", "n/a": "n/a"}


def _load(results: Path, name: str):
    path = results / name
    return load_json(path) if path.is_file() else None


def _n(value) -> str:
    return f"{value:,}" if isinstance(value, int) else str(value)


def _median(values):
    if not values:
        return "–"
    m = statistics.median(values)
    return _n(int(m)) if float(m).is_integer() else f"{m:,.1f}"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def render(results: Path = RESULTS_DIR) -> str:
    fp = _load(results, "footprint.json")
    probes = _load(results, "probes.json")
    golden = _load(results, "golden.json")
    install = _load(results, "install.json")
    runs = _load(results, "runs.json")
    lines = ["# Harness benchmark report", "",
             "Generated by `python -m cbench report` from the JSON files in this directory. "
             "Every number below is recomputed by `python -m cbench verify`.", ""]

    if fp:
        prov = fp["provenance"]
        lines += ["## Provenance", "",
                  f"- Lockfile sha256 `{prov['lockfile_sha256'][:16]}`; pricing sha256 `{prov['pricing_sha256'][:16]}` (as of {fp['pricing_as_of']})",
                  f"- Tokenizer `{prov['tokenizer']['id']}` sha256 `{prov['tokenizer']['sha256'][:16]}` ({prov['tokenizer']['kind']})",
                  f"- Canonical install root `{prov['canonical_root']}`", ""]
        rows = []
        for name, r in fp["frameworks"].items():
            det = install["frameworks"][name]["deterministic"] if install and name in install["frameworks"] else "–"
            rows.append([name, f"`{(r['sha'] or '—')[:10]}`", _n(r["install"]["files"]),
                         f"`{r['install']['tree_sha256'][:12]}`", str(det)])
        lines += _table(["Framework", "Pinned commit", "Installed files", "Install tree hash", "Installs identically twice"], rows) + [""]

        lines += ["## Tier 1: context footprint", "",
                  "Token counts use the pinned proxy tokenizer. *Always-on* is paid on every request; "
                  "*workflow* is the documented plan-to-code path, from each step's own file (lower) to "
                  "that file plus everything it references or packages (upper).", ""]
        rows = []
        for name, r in fp["frameworks"].items():
            a, w = r["always_on"], r["workflow"]
            rows.append([name, _n(a["listing_tokens"]), _n(a["session_start_tokens"]), _n(a["memory_tokens"]),
                         f"**{_n(a['total_tokens'])}**", _n(r["corpus_tokens"]),
                         f"{_n(w['lower_tokens'])} – {_n(w['upper_tokens'])}", str(len(w["steps"]))])
        lines += _table(["Framework", "Listing", "SessionStart", "CLAUDE.md", "Always-on", "Corpus", "Workflow tokens", "Steps"], rows) + [""]

        lines += [f"### Cost on {HEADLINE_MODEL}", ""]
        rows = []
        for name, r in fp["frameworks"].items():
            c = r["cost_usd"][HEADLINE_MODEL]
            rows.append([name, f"${c['always_on_per_request_uncached']}", f"${c['always_on_per_request_cache_read']}",
                         f"${c['always_on_100_requests_cached']}",
                         f"${c['workflow_load_lower']} – ${c['workflow_load_upper']}"])
        lines += _table(["Framework", "Always-on / request (uncached)", "Always-on / request (cache read)",
                         "Always-on over 100 cached requests", "Loading the workflow once"], rows) + [""]
        models = sorted(next(iter(fp["frameworks"].values()))["cost_usd"])
        rows = []
        for name, r in fp["frameworks"].items():
            rows.append([name] + [f"${r['cost_usd'][m]['workflow_load_upper']}" for m in models])
        lines += ["### Workflow load cost (upper bound) by model", ""]
        lines += _table(["Framework"] + models, rows) + [""]

    if probes:
        idx = probes["scenario_index"]
        lines += ["## Tier 2: golden hook probes", "",
                  "Each cell is the combined decision of the framework's installed hooks for one replayed action. "
                  "`·` means no hook is registered for that event; `n/a` means the framework has no such artifact. "
                  "*Meets intent* counts scenarios where the decision matches what a process-enforcing harness "
                  "should do (S08 is informational and not scored).", ""]
        header = ["Framework / host"] + list(idx) + ["Meets intent"]
        rows = []
        for name, r in probes["frameworks"].items():
            for host, h in r["hosts"].items():
                cells = []
                for sid in idx:
                    s = h["scenarios"][sid]
                    cell = SYMBOL[s["verdict"]]
                    if s["verdict"] == "block":
                        vias = sorted({e["via"] for e in s["hooks"] if e["verdict"] == "block"})
                        if any(v.startswith("fail-closed") for v in vias):
                            cell += "†"
                    cells.append(cell)
                rows.append([f"{name} / {host}"] + cells + [f"{h['score']['met']}/{h['score']['scored']}"])
        lines += _table(header, rows) + [""]
        lines += ["† blocked only because the hook failed (non-zero exit or non-JSON output) and is registered `failClosed`, "
                  "not because it returned a deny decision.", ""]
        rows = [[sid, s["slug"], s["intent"], s["title"]] for sid, s in idx.items()]
        lines += _table(["ID", "Scenario", "Intent", "Action"], rows) + [""]

    if golden:
        lines += ["## Golden tasks", ""]
        rows = [[t, str(r["valid"]), f"{r['before']['passed']}/{r['before']['total']}",
                 f"{r['after']['passed']}/{r['after']['total']}", f"`{r['task_sha256'][:12]}`"]
                for t, r in golden["tasks"].items()]
        lines += _table(["Task", "Valid", "Hidden tests on untouched repo", "With reference patch", "Task hash"], rows) + [""]

    lines += ["## Tier 3: live runs", ""]
    if not runs or not runs["runs"]:
        lines += ["No live runs are recorded yet. Record them with "
                  "`ANTHROPIC_API_KEY=... python -m cbench live --trials 3`, then `python -m cbench grade` and "
                  "`python -m cbench report`.", ""]
    else:
        groups: dict[tuple, list] = {}
        for r in runs["runs"]:
            groups.setdefault((r["framework"], r["task"], r["model"]), []).append(r)
        base_first = {}
        for (fw, task, model), rs in groups.items():
            if fw == "baseline":
                base_first[(task, model)] = [r["usage"]["first_request_input_tokens"] for r in rs
                                             if r["usage"]["first_request_input_tokens"] is not None]
        rows = []
        for (fw, task, model), rs in sorted(groups.items()):
            totals = [sum(r["usage"]["totals"].values()) for r in rs]
            outputs = [r["usage"]["totals"]["output_tokens"] for r in rs]
            costs = [float(r["cost_usd"]) for r in rs if r["cost_usd"] is not None]
            firsts = [r["usage"]["first_request_input_tokens"] for r in rs if r["usage"]["first_request_input_tokens"] is not None]
            overhead = "–"
            if fw != "baseline" and firsts and base_first.get((task, model)):
                overhead = _n(int(statistics.median(firsts) - statistics.median(base_first[(task, model)])))
            ok_integrity = all(all(r["integrity"].values()) for r in rs)
            rows.append([fw, task, model, f"{sum(r['resolved'] for r in rs)}/{len(rs)}", _median(totals),
                         _median(outputs), f"${statistics.median(costs):.4f}" if costs else "–",
                         overhead, "yes" if ok_integrity else "**no**"])
        lines += _table(["Framework", "Task", "Model", "Resolved", "Median total tokens", "Median output tokens",
                         "Median cost", "First-request overhead vs baseline", "Records intact"], rows) + [""]
        lines += ["Cost is recomputed from recorded token usage and `pricing.json` (cache writes priced at the 5-minute rate). "
                  "First-request overhead is the median first-request input tokens minus the baseline's for the same task "
                  "and model: the exact always-on cost of the framework as Claude Code actually sent it.", ""]
    return "\n".join(lines).rstrip() + "\n"


def build(results: Path = RESULTS_DIR) -> Path:
    out = results / "REPORT.md"
    out.write_text(render(results), encoding="utf-8")
    return out
