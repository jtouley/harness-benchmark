"""Tier 3 on Harbor: generate one Harbor task per (golden task, framework arm).

``python -m cbench harbor-build`` writes ``harbor/tasks/<task>--<arm>/``. Every
file is derived from ``frameworks.lock.json`` and ``golden/tasks``, so the lockfile
stays the single source of truth: the Dockerfile fetches the pinned sha, then runs
the lockfile's own build and install ops. Nothing under ``harbor/tasks`` is
hand-edited; ``harbor-build --check`` fails when it has drifted.

Layout of a generated task (Harbor task format)::

    instruction.md       the arm's drive prompt with the issue filled in
    task.toml            timeouts, resources
    environment/         Dockerfile + repo/ (the task's starting repository)
    tests/               test.sh + hidden/ (uploaded only at verification time)
    solution/            solve.sh + reference.patch (used by the `oracle` agent)
"""

from __future__ import annotations

import json
import shlex
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path

from .lock import Framework, Lock, load_lock
from .util import BENCH_ROOT, GOLDEN_DIR, load_json, sha256_text

HARBOR_DIR = BENCH_ROOT / "harbor"
TASKS_DIR = HARBOR_DIR / "tasks"

SRC, HOME, PROJ = "/opt/fw", "/root", "/app"

# Versions are pinned: a different Claude Code or uv is a different experiment.
CLAUDE_CODE_VERSION = "2.1.294"
UV_VERSION = "0.11.0"
BASE_NODE = "mirror.gcr.io/library/node:22-bookworm"
BASE_PYTHON = "mirror.gcr.io/library/python:3.12-bookworm"

TASK_TOML = """\
schema_version = "1.1"

[task]
name = "harness-benchmark/{name}"
description = "{title}. Arm: {arm}."
keywords = ["harness-benchmark", "{arm}", "{task}"]

[metadata]
task = "{task}"
arm = "{arm}"
framework_sha = "{sha}"
lock_sha256 = "{lock_sha}"

[verifier]
timeout_sec = 300.0

[agent]
timeout_sec = {agent_timeout}

[environment]
build_timeout_sec = 1800.0
cpus = 2
memory_mb = 4096
storage_mb = 8192
"""

TEST_SH = """\
#!/bin/bash
# Hidden tests: uploaded by Harbor after the agent finishes, never visible to it.
# reward = 1.0 only when every hidden test passes; pass counts are kept for the report.
set -u
mkdir -p /logs/verifier
cd {proj}
rm -rf _hidden_tests && cp -r /tests/hidden _hidden_tests
python3 -m pytest -q -p no:cacheprovider -p no:randomly --junitxml=/tmp/junit.xml \\
    --rootdir {proj} _hidden_tests > /logs/verifier/pytest.txt 2>&1
python3 - <<'PY'
import json, xml.etree.ElementTree as ET
passed = total = 0
try:
    for case in ET.parse("/tmp/junit.xml").getroot().iter("testcase"):
        total += 1
        if not any(c.tag in ("failure", "error", "skipped") for c in case):
            passed += 1
except Exception:
    pass
json.dump({{"reward": 1.0 if total and passed == total else 0.0, "tests_passed": passed, "tests_total": total}},
          open("/logs/verifier/reward.json", "w"))
print(f"hidden tests: {{passed}}/{{total}}")
PY
"""

SOLVE_SH = """\
#!/bin/bash
set -e
cd {proj}
git apply --whitespace=nowarn /solution/reference.patch
"""


def sub(text: str) -> str:
    return text.replace("{src}", SRC).replace("{home}", HOME).replace("{proj}", PROJ)


def _ops(ops: list[dict], default_cwd: str) -> list[str]:
    lines = []
    for op in ops:
        kind = op["op"]
        if kind == "mkdir":
            lines.append(f"RUN mkdir -p {shlex.quote(sub(op['path']))}")
        elif kind == "run":
            cwd = sub(op.get("cwd", default_cwd))
            argv = " ".join(shlex.quote(sub(a)) for a in op["argv"])
            lines.append(f"RUN cd {shlex.quote(cwd)} && {argv}")
        else:
            raise ValueError(f"harbor-build cannot translate lockfile op {kind!r}; use `run` ops that follow the framework's README")
    return lines


def dockerfile(fw: Framework, *, proxy_ca: bool = False) -> str:
    out = [
        "# Generated by `python -m cbench harbor-build`. Do not edit.",
        f"FROM {BASE_NODE} AS node",
        f"FROM {BASE_PYTHON}",
        "COPY --from=node /usr/local/bin/node /usr/local/bin/node",
        "COPY --from=node /usr/local/lib/node_modules /usr/local/lib/node_modules",
        "RUN ln -s ../lib/node_modules/npm/bin/npm-cli.js /usr/local/bin/npm \\",
        " && ln -s ../lib/node_modules/npm/bin/npx-cli.js /usr/local/bin/npx",
    ]
    if proxy_ca:
        out += [
            "# Sandboxes that re-terminate TLS: trust their CA (bench-proxy-ca.crt next to this file).",
            "COPY bench-proxy-ca.crt /usr/local/share/ca-certificates/bench-proxy-ca.crt",
            "ENV NODE_EXTRA_CA_CERTS=/usr/local/share/ca-certificates/bench-proxy-ca.crt \\",
            "    SSL_CERT_FILE=/usr/local/share/ca-certificates/bench-proxy-ca.crt \\",
            "    GIT_SSL_CAINFO=/usr/local/share/ca-certificates/bench-proxy-ca.crt \\",
            "    REQUESTS_CA_BUNDLE=/usr/local/share/ca-certificates/bench-proxy-ca.crt \\",
            "    PIP_CERT=/usr/local/share/ca-certificates/bench-proxy-ca.crt",
        ]
    out += [
        "ENV CI=1 DO_NOT_TRACK=1 OPENSPEC_TELEMETRY=0 DISABLE_AUTOUPDATER=1 PYTHONDONTWRITEBYTECODE=1",
        f"RUN pip install --no-cache-dir -q uv=={UV_VERSION} pytest",
        f"RUN npm install -g @anthropic-ai/claude-code@{CLAUDE_CODE_VERSION}",
    ]
    if fw.repo:
        out += [
            f"# {fw.name} @ {fw.sha}",
            f"RUN git init -q {SRC} && cd {SRC} \\",
            f" && git fetch -q --depth 1 {fw.repo} {fw.sha} && git checkout -q FETCH_HEAD \\",
            f' && test "$(git rev-parse HEAD)" = "{fw.sha}"',
            *_ops(fw.build, SRC),
        ]
    out += [
        f"COPY repo/ {PROJ}/",
        f"RUN cd {PROJ} && git init -q -b main && git config user.email bench@example.invalid \\",
        " && git config user.name bench && git add -A && git commit -q -m base",
    ]
    if fw.install:
        out += ["# Install exactly as the lockfile says (the framework's documented route).", *_ops(fw.install, PROJ)]
    out += [
        f"RUN cd {PROJ} && git add -A && git commit -q --allow-empty -m 'framework install'",
        f"WORKDIR {PROJ}",
        "",
    ]
    return "\n".join(out)


def task_name(task_id: str, arm: str) -> str:
    return f"{task_id.lower()}--{arm}"


def build_task(fw: Framework, task_dir: Path, lock: Lock, dest: Path, *, proxy_ca: Path | None = None) -> None:
    meta = load_json(task_dir / "task.json")
    issue = (task_dir / meta["issue"]).read_text(encoding="utf-8").strip()
    if dest.exists():
        shutil.rmtree(dest)
    (dest / "environment").mkdir(parents=True)
    (dest / "tests").mkdir()
    (dest / "solution").mkdir()

    (dest / "instruction.md").write_text(fw.drive_prompt.format(issue=issue) + lock.drive_suffix + "\n", encoding="utf-8")
    (dest / "task.toml").write_text(TASK_TOML.format(
        name=dest.name, title=meta["title"].replace('"', "'"), arm=fw.name, task=meta["id"],
        sha=fw.sha or "none", lock_sha=lock.sha256, agent_timeout="1800.0"), encoding="utf-8")

    shutil.copytree(task_dir / "repo", dest / "environment" / "repo")
    (dest / "environment" / "Dockerfile").write_text(dockerfile(fw, proxy_ca=proxy_ca is not None), encoding="utf-8")
    if proxy_ca is not None:
        shutil.copy(proxy_ca, dest / "environment" / "bench-proxy-ca.crt")

    shutil.copytree(task_dir / meta["hidden"], dest / "tests" / "hidden")
    (dest / "tests" / "test.sh").write_text(TEST_SH.format(proj=PROJ), encoding="utf-8")
    shutil.copy(task_dir / "reference.patch", dest / "solution" / "reference.patch")
    (dest / "solution" / "solve.sh").write_text(SOLVE_SH.format(proj=PROJ), encoding="utf-8")
    for script in (dest / "tests" / "test.sh", dest / "solution" / "solve.sh"):
        script.chmod(0o755)


def generate(arms: list[str] | None = None, tasks: list[str] | None = None, *, out: Path = TASKS_DIR,
             proxy_ca: Path | None = None) -> list[Path]:
    lock = load_lock()
    names = arms or list(lock.frameworks)
    written = []
    for task_dir in sorted((GOLDEN_DIR / "tasks").iterdir()):
        if tasks and task_dir.name not in tasks:
            continue
        for arm in names:
            dest = out / task_name(task_dir.name, arm)
            build_task(lock.frameworks[arm], task_dir, lock, dest, proxy_ca=proxy_ca)
            written.append(dest)
    return written


def digest_tree(root: Path) -> str:
    rows = [f"{p.relative_to(root)}\t{sha256_text(p.read_text(errors='replace'))}\n"
            for p in sorted(root.rglob("*")) if p.is_file()]
    return sha256_text("".join(rows))


def check() -> int:
    """Regenerate into a scratch dir and compare with the committed harbor/tasks."""
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        scratch = Path(tmp) / "tasks"
        generate(out=scratch)
        if TASKS_DIR.is_dir() and digest_tree(scratch) == digest_tree(TASKS_DIR):
            print("ok   harbor/tasks matches the lockfile and golden tasks")
            return 0
    print("FAIL harbor/tasks differs from what the lockfile and golden tasks generate; run `python -m cbench harbor-build`")
    return 1


def collect(jobs_dir: Path) -> dict:
    """Read Harbor trial results (``<job>/<trial>/result.json``) into one record per trial."""
    trials = []
    for path in sorted(jobs_dir.glob("*/*/result.json")):
        r = json.loads(path.read_text(encoding="utf-8"))
        if "task_name" not in r:
            continue
        name = r["task_name"].split("/")[-1]
        task, _, arm = name.partition("--")
        ctx = r.get("agent_result") or {}
        rewards = (r.get("verifier_result") or {}).get("rewards") or {}
        trials.append({
            "job": path.parent.parent.name,
            "trial": r.get("trial_name"),
            "task": task,
            "arm": arm,
            "model": ((r.get("config") or {}).get("agent") or {}).get("model_name"),
            "reward": rewards.get("reward"),
            "tests_passed": rewards.get("tests_passed"),
            "tests_total": rewards.get("tests_total"),
            "input_tokens": ctx.get("n_input_tokens"),
            "cache_tokens": ctx.get("n_cache_tokens"),
            "output_tokens": ctx.get("n_output_tokens"),
            "cost_usd": ctx.get("cost_usd"),
            "error": (r.get("exception_info") or {}).get("exception_type"),
        })
    return {"schema": 1, "trials": trials}
