"""A postmortem of one batch of runs, generated from the records: postmortems/<batch>.md.

    python -m loop.postmortem 2026-10-21-cadence-core-subscription [--notes postmortems/<batch>.notes.json]

The sections are fixed: Summary, Timeline, Evidence ledger (VERIFIED / CLAIMED / CONTRADICTED), Root
causes, Decisions, Actions. The generator writes Summary and Timeline, the VERIFIED ledger rows (one per
scored run) and the root causes (the findings in findings.jsonl that cite the batch's runs). Hand-written
lines come from the notes file: {"ledger": [{"status", "claim", "run_ids"}], "root_causes": [...],
"decisions": [...], "actions": [...]}, each item {"text", "run_ids"}. A hand-written line with no run id,
or with a run id that has no record, is refused.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from loop import findings, record, scoreboard

ROOT = Path(__file__).resolve().parents[1]
STATUSES = ("VERIFIED", "CLAIMED", "CONTRADICTED")
SECTIONS = ("Summary", "Timeline", "Speed", "Evidence ledger", "Root causes", "Decisions", "Actions")


class PostmortemError(Exception):
    pass


def _cite(ids: list[str]) -> str:
    return ", ".join(f"`{i}`" for i in ids)


def notes_problems(notes: dict, runs: Path) -> list[str]:
    problems = []
    for section in ("ledger", "root_causes", "decisions", "actions"):
        for i, item in enumerate(notes.get(section, []), 1):
            ids = item.get("run_ids")
            where = f"{section}[{i}]"
            if not isinstance(ids, list) or not ids:
                problems.append(f"{where}: a hand-written line cites no run id")
                continue
            for rid in ids:
                if not record.RUN_ID.fullmatch(str(rid)) or not (runs / str(rid) / "record.json").exists():
                    problems.append(f"{where}: {rid!r} is not a run id with a record")
            if section == "ledger" and item.get("status") not in STATUSES:
                problems.append(f"{where}: status must be one of {STATUSES}")
            if not (item.get("claim") if section == "ledger" else item.get("text")):
                problems.append(f"{where}: empty")
    return problems


def generate(batch: str, runs: Path, notes: dict, findings_path: Path = findings.FINDINGS) -> str:
    problems = notes_problems(notes, runs)
    if problems:
        raise PostmortemError("; ".join(problems))
    rows = []
    for run in sorted(p for p in runs.iterdir() if (p / "record.json").exists()):
        rec = record.load(run)
        if rec["batch"] == batch:
            scores = record.scores(run)
            rows.append((rec, scores[-1] if scores else None))
    if not rows:
        raise PostmortemError(f"no run of batch {batch} in {runs}")
    rows.sort(key=lambda r: (r[0]["started_at"] or "", r[0]["run_id"]))
    counted = [(r, s) for r, s in rows if r["counts"]["counts"] and s]
    shas = sorted({(r.get("cadence") or {}).get("sha", "")[:7] for r, _ in rows} - {""})
    models = sorted({m for r, _ in rows for m in (r["models_served"] or [r["model_requested"] or "unknown"])})
    out = [f"# Postmortem: {batch}", "",
           "Generated by `python -m loop.postmortem` from `runs/`, `findings.jsonl` and the notes file. "
           "Do not edit by hand.", ""]

    out += ["## Summary", "",
            f"- Runs: {len(rows)}; counted with a score: {len(counted)}; not counted: {len(rows) - len(counted)}.",
            f"- Cadence: {', '.join(shas) or 'none'}. Models served: {', '.join(models)}.",
            f"- Checks passed (counted): {', '.join(f'{s['passed']}/{s['total']}' for _, s in counted) or 'none'}.",
            ""]

    out += ["## Timeline", "", "| Start (UTC) | Run | Task | Stop | Reason | Score | Counts |", "|---|---|---|---|---|---|---|"]
    for rec, score in rows:
        sp = rec["stop_point"]
        got = f"{score['passed']}/{score['total']}" if score else "not scored"
        out.append(f"| {rec['started_at'] or 'not recorded'} | `{rec['run_id']}` | {rec['task']} | {sp['block'] or '—'} | "
                   f"{sp['reason'] or '—'} | {got} | {'yes' if rec['counts']['counts'] else 'no: ' + rec['counts']['why']} |")
    out.append("")

    out += _speed(rows, runs)

    out += ["## Evidence ledger", "", "| Status | Claim | Runs |", "|---|---|---|"]
    for rec, score in counted:
        tree = (score["grader"].get("tree") or "unknown")[:7]
        out.append(f"| VERIFIED | {rec['task']} scored {score['passed']}/{score['total']} (reward {score['reward']}) "
                   f"with the harness-benchmark grader, tree {tree} | `{rec['run_id']}` |")
    for item in sorted(notes.get("ledger", []), key=lambda i: STATUSES.index(i["status"])):
        out.append(f"| {item['status']} | {item['claim']} | {_cite(item['run_ids'])} |")
    out.append("")

    ids = {r["run_id"] for r, _ in rows}
    out += ["## Root causes", ""]
    for row in findings.load(findings_path):
        cited = [i for i in row["run_ids"] if i in ids]
        if cited:
            out.append(f"- **{row['id']}** ({row['status']}): {row['title']}. {row['root_cause']}. Runs: {_cite(cited)}.")
    out += [f"- {i['text'].rstrip('.')}. Runs: {_cite(i['run_ids'])}." for i in notes.get("root_causes", [])]
    out.append("")
    for title, key in (("Decisions", "decisions"), ("Actions", "actions")):
        out += [f"## {title}", ""]
        out += [f"- {i['text'].rstrip('.')}. Runs: {_cite(i['run_ids'])}." for i in notes.get(key, [])] or ["- None recorded."]
        out.append("")
    return "\n".join(out)


def _speed(rows: list[tuple[dict, dict | None]], runs: Path) -> list[str]:
    """Agent time per run against the one-shot of the same task and model, the slowest runs, and time per
    block when the record has it."""
    out = ["## Speed", "",
           f"Agent session per run, and its ratio to the mean one-shot session of the same task and model "
           f"(stretch goal: at most {scoreboard.STRETCH_RATIO}).", "",
           "| Run | Task | Model | Agent min | One-shot min | Ratio | Stop |", "|---|---|---|---|---|---|---|"]
    timed = []
    for rec, _ in rows:
        seconds = rec["timing"]["agent_wall_seconds"]
        base = scoreboard.oneshot_seconds(runs, rec["task"], rec["model_requested"])
        ratio = scoreboard.time_ratio(runs, rec)
        if seconds is not None:
            timed.append((seconds, rec["run_id"]))
        out.append(f"| `{rec['run_id']}` | {rec['task']} | {rec['model_requested']} | "
                   f"{f'{seconds / 60:.1f}' if seconds is not None else 'not recorded'} | "
                   f"{f'{base / 60:.1f}' if base else '—'} | {f'{ratio:.2f}' if ratio is not None else '—'} | "
                   f"{rec['stop_point']['block'] or '—'} |")
    slowest = sorted(timed, reverse=True)[:3]
    out += ["", "Slowest runs: " + (", ".join(f"`{rid}` ({s / 60:.1f} min)" for s, rid in slowest) or "none timed") + "."]
    blocks: dict[str, float] = {}
    for rec, _ in rows:
        for block, seconds in (rec["timing"]["blocks"] or {}).items():
            blocks[block] = blocks.get(block, 0.0) + float(seconds)
    if blocks:
        top = sorted(blocks.items(), key=lambda kv: -kv[1])[:5]
        out.append("Time per block (all runs): " + ", ".join(f"{b} {s / 60:.1f} min" for b, s in top) + ".")
    else:
        out.append("Time per block: not measured in these records (the driver records it from B2 on).")
    out.append("")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m loop.postmortem", description=__doc__.split("\n\n")[0])
    ap.add_argument("batch")
    ap.add_argument("--runs", type=Path, default=ROOT / "runs")
    ap.add_argument("--notes", type=Path)
    ap.add_argument("--out", type=Path)
    args = ap.parse_args(argv)
    notes_path = args.notes or ROOT / "postmortems" / f"{args.batch}.notes.json"
    notes = json.loads(notes_path.read_text(encoding="utf-8")) if notes_path.exists() else {}
    try:
        text = generate(args.batch, args.runs, notes)
    except PostmortemError as exc:
        print(f"refused: {exc}", file=sys.stderr)
        return 2
    out = args.out or ROOT / "postmortems" / f"{args.batch}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
