"""A postmortem of one batch of runs, generated from the records: postmortems/<batch>.md.

    python -m loop.postmortem 2026-10-21-cadence-core-subscription [--notes postmortems/<batch>.notes.json]
    python -m loop.postmortem --all                 # every committed postmortem again, from its notes
    python -m loop.postmortem --run <run id>        # the Trace row of one run, printed

A postmortem named <name> covers the batches its notes file lists under "batches", else the one batch
<name>. loop.driver refreshes every postmortem that covers a run's batch when it records the run, and
writes <batch>.md when none does; loop.check refuses a committed postmortem that is not what the
generator writes, and a counted or cited run that is in none (runs/README.md, "After a merge").

The sections are fixed: Summary, Timeline, Speed, Diagnosis, Trace, Evidence ledger (VERIFIED / CLAIMED /
CONTRADICTED), Root causes, Decisions, Actions. The generator writes Summary and Timeline, the VERIFIED
ledger rows (one per scored run) and the root causes (the findings in findings.jsonl that cite the batch's
runs). Trace lists, per run, the findings that cite it and the cadence commits and pull requests that cite
it, from citations.json (loop.trace). Hand-written lines come from the notes file: {"ledger": [{"status",
"claim", "run_ids"}], "root_causes": [...], "decisions": [...], "actions": [...]}, each item {"text",
"run_ids"}. A hand-written line with no run id, or with a run id that has no record, is refused.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from loop import findings, record, scoreboard, trace

ROOT = Path(__file__).resolve().parents[1]
POSTMORTEMS = ROOT / "postmortems"
STATUSES = ("VERIFIED", "CLAIMED", "CONTRADICTED")
SECTIONS = ("Summary", "Timeline", "Speed", "Diagnosis", "Trace", "Evidence ledger", "Root causes", "Decisions",
            "Actions")


class PostmortemError(Exception):
    pass


def _cite(ids: list[str]) -> str:
    return ", ".join(f"`{i}`" for i in ids)


def notes_problems(notes: dict, runs: Path) -> list[str]:
    problems = []
    for section in ("ledger", "root_causes", "decisions", "actions", "reference_diffs"):
        for i, item in enumerate(notes.get(section, []), 1):
            ids = item.get("run_ids")
            where = f"{section}[{i}]"
            if not isinstance(ids, list) or not ids:
                problems.append(f"{where}: a hand-written line cites no run id")
                continue
            for rid in ids:
                if not record.RUN_ID.fullmatch(str(rid)) or not (runs / str(rid) / "record.json").exists():
                    problems.append(f"{where}: {rid!r} is not a run id with a record")
            if section == "ledger" and item.get("status") not in STATUSES:
                problems.append(f"{where}: status must be one of {STATUSES}")
            if not (item.get("claim") if section == "ledger" else item.get("text")):
                problems.append(f"{where}: empty")
    return problems


def generate(batch: str | list[str], runs: Path, notes: dict, findings_path: Path = findings.FINDINGS,
             title: str | None = None, citations: dict | None = None) -> str:
    """The postmortem of one batch, or of several (`batch` a list) under `title`. `citations` is the
    loop.trace snapshot; the committed citations.json when None."""
    batches = [batch] if isinstance(batch, str) else list(batch)
    title = title or ", ".join(batches)
    problems = notes_problems(notes, runs)
    if problems:
        raise PostmortemError("; ".join(problems))
    rows = []
    for run in sorted(p for p in runs.iterdir() if (p / "record.json").exists()):
        rec = record.load(run)
        if rec["batch"] in batches:
            scores = record.scores(run)
            rows.append((rec, scores[-1] if scores else None))
    if not rows:
        raise PostmortemError(f"no run of batch {', '.join(batches)} in {runs}")
    rows.sort(key=lambda r: (r[0]["started_at"] or "", r[0]["run_id"]))
    counted = [(r, s) for r, s in rows if r["counts"]["counts"] and s]
    shas = sorted({(r.get("cadence") or {}).get("sha", "")[:7] for r, _ in rows} - {""})
    models = sorted({m for r, _ in rows for m in (r["models_served"] or [r["model_requested"] or "unknown"])})
    out = [f"# Postmortem: {title}", "",
           "Generated by `python -m loop.postmortem` from `runs/`, `findings.jsonl` and the notes file. "
           "Do not edit by hand.", ""]

    out += ["## Summary", "",
            f"- Runs: {len(rows)}; counted with a score: {len(counted)}; not counted: {len(rows) - len(counted)}.",
            f"- Cadence: {', '.join(shas) or 'none'}. Models served: {', '.join(models)}.",
            f"- Checks passed (counted): {', '.join(f'{s['passed']}/{s['total']}' for _, s in counted) or 'none'}.",
            ""]

    out += ["## Timeline", "", "| Start (UTC) | Run | Task | Stop | Reason | Score | Counts |", "|---|---|---|---|---|---|---|"]
    for rec, score in rows:
        sp = rec["stop_point"]
        got = f"{score['passed']}/{score['total']}" if score else "not scored"
        out.append(f"| {rec['started_at'] or 'not recorded'} | `{rec['run_id']}` | {rec['task']} | {sp['block'] or '—'} | "
                   f"{sp['reason'] or '—'} | {got} | {'yes' if rec['counts']['counts'] else 'no: ' + rec['counts']['why']} |")
    out.append("")

    out += _speed(rows, runs)
    out += _diagnosis(rows, notes, findings_path)
    out += _trace(rows, runs, findings_path, citations)

    out += ["## Evidence ledger", "", "| Status | Claim | Runs |", "|---|---|---|"]
    for rec, score in counted:
        tree = (score["grader"].get("tree") or "unknown")[:7]
        out.append(f"| VERIFIED | {rec['task']} scored {score['passed']}/{score['total']} (reward {score['reward']}) "
                   f"with the harness-benchmark grader, tree {tree} | `{rec['run_id']}` |")
    for item in sorted(notes.get("ledger", []), key=lambda i: STATUSES.index(i["status"])):
        out.append(f"| {item['status']} | {item['claim']} | {_cite(item['run_ids'])} |")
    out.append("")

    ids = {r["run_id"] for r, _ in rows}
    out += ["## Root causes", ""]
    for row in findings.load(findings_path):
        cited = [i for i in row["run_ids"] if i in ids]
        if cited:
            out.append(f"- **{row['id']}** ({row['status']}): {row['title']}. {row['root_cause']}. Runs: {_cite(cited)}.")
    out += [f"- {i['text'].rstrip('.')}. Runs: {_cite(i['run_ids'])}." for i in notes.get("root_causes", [])]
    out.append("")
    for title, key in (("Decisions", "decisions"), ("Actions", "actions")):
        out += [f"## {title}", ""]
        out += [f"- {i['text'].rstrip('.')}. Runs: {_cite(i['run_ids'])}." for i in notes.get(key, [])] or ["- None recorded."]
        out.append("")
    return "\n".join(out)


def _speed(rows: list[tuple[dict, dict | None]], runs: Path) -> list[str]:
    """Agent time per run against the one-shot of the same task and model, the slowest runs, and time per
    block when the record has it."""
    out = ["## Speed", "",
           f"Agent session per run, and its ratio to the mean one-shot session of the same task and model "
           f"(stretch goal: at most {scoreboard.STRETCH_RATIO}). A run that stopped before the end with no check "
           f"passed has no ratio: its time says nothing about a finished pipeline.", "",
           "| Run | Task | Model | Agent min | One-shot min | Ratio | Stop |", "|---|---|---|---|---|---|---|"]
    timed = []
    for rec, _ in rows:
        seconds = rec["timing"]["agent_wall_seconds"]
        base = scoreboard.oneshot_seconds(runs, rec["task"], rec["model_requested"])
        ratio = scoreboard.time_ratio(runs, rec)
        ratio_text = f"{ratio:.2f}" if ratio is not None else (
            "— (stopped early)" if seconds is not None and base and not scoreboard.reached_end(runs, rec) else "—")
        if seconds is not None:
            timed.append((seconds, rec["run_id"]))
        out.append(f"| `{rec['run_id']}` | {rec['task']} | {rec['model_requested']} | "
                   f"{f'{seconds / 60:.1f}' if seconds is not None else 'not recorded'} | "
                   f"{f'{base / 60:.1f}' if base else '—'} | {ratio_text} | "
                   f"{rec['stop_point']['block'] or '—'} |")
    slowest = sorted(timed, reverse=True)[:3]
    out += ["", "Slowest runs: " + (", ".join(f"`{rid}` ({s / 60:.1f} min)" for s, rid in slowest) or "none timed") + "."]
    stages: dict[str, dict] = {}
    for rec, _ in rows:
        for stage, t in (record.blocks(runs / rec["run_id"], rec) or {}).items():
            agg = stages.setdefault(stage, {"seconds": 0.0, "calls": 0, "runs": 0})
            agg["seconds"] += t["seconds"]
            agg["calls"] += t["calls"]
            agg["runs"] += 1
    if not stages:
        out.append("Time per block: not measured in these records (loop.blocks, from the run's attest logs).")
    else:
        out += ["", "Peer time per block, all runs (loop.blocks; orchestrator time between peers is in no block). "
                "Repeat rounds are peer calls beyond one per run.", "",
                "| Block (stage) | Peer min | Peer calls | Runs | Repeat rounds |", "|---|---|---|---|---|"]
        for stage, agg in sorted(stages.items(), key=lambda kv: -kv[1]["seconds"]):
            out.append(f"| {stage} | {agg['seconds'] / 60:.1f} | {agg['calls']} | {agg['runs']} | "
                       f"{agg['calls'] - agg['runs']} |")
        loops = sum(agg["calls"] - agg["runs"] for agg in stages.values())
        loop_min = sum(agg["seconds"] * (agg["calls"] - agg["runs"]) / agg["calls"] for agg in stages.values() if agg["calls"])
        out += ["", f"Time in loops (repeat rounds, at each block's mean peer time): about {loop_min / 60:.1f} min "
                f"over {loops} repeat calls."]
    out.append("")
    return out


def _trace(rows: list[tuple[dict, dict | None]], runs: Path, findings_path: Path, citations: dict | None) -> list[str]:
    """Each run: the findings that cite it, and the cadence commits and pull requests that cite it as evidence."""
    snap = trace.load_citations() if citations is None else citations
    at = f" at cadence main `{snap['main'][:7]}`" if snap.get("main") else ""
    out = ["## Trace", "",
           f"Per run: the findings (findings.jsonl) that cite it, and the cadence commits that cite it with an "
           f"`Evidence:` trailer, with each commit's finding, pull request and status (citations.json{at}; "
           f"`python -m loop.trace snapshot` refreshes it).", "",
           trace.table(trace.rows(runs, findings_path, snap, [rec["run_id"] for rec, _ in rows])), ""]
    return out


def _diagnosis(rows: list[tuple[dict, dict | None]], notes: dict, findings_path: Path) -> list[str]:
    """Each run: the block it stopped at, why, its agent minutes, its checks, and the findings that cite it;
    then the findings ranked by the counted runs they cite, then by those runs' minutes. A run that two
    findings cite counts under both."""
    cited: dict[str, list[str]] = {}
    for row in findings.load(findings_path):
        for rid in row["run_ids"]:
            cited.setdefault(rid, []).append(row["id"])
    out = ["## Diagnosis", "",
           "| Run | Task | Stop | Cause | Agent min | Checks | Counts | Findings |", "|---|---|---|---|---|---|---|---|"]
    cost: dict[str, list[float]] = {}
    for rec, score in rows:
        seconds = rec["timing"]["agent_wall_seconds"]
        ids = cited.get(rec["run_id"], [])
        counts = rec["counts"]["counts"] and score is not None
        out.append(f"| `{rec['run_id']}` | {rec['task']} | {rec['stop_point']['block'] or '—'} | "
                   f"{rec['stop_point']['reason'] or '—'} | {f'{seconds / 60:.1f}' if seconds is not None else '—'} | "
                   f"{f'{score['passed']}/{score['total']}' if score else '—'} | "
                   f"{'yes' if counts else 'not counted'} | {', '.join(ids) or '—'} |")
        if counts:
            for fid in ids:
                cost.setdefault(fid, []).append((seconds or 0) / 60)
    out += ["", "Findings by cost (counted runs of these batches that cite each finding, then their agent minutes):", "",
            "| Finding | Runs | Minutes |", "|---|---|---|"]
    for fid, minutes in sorted(cost.items(), key=lambda kv: (-len(kv[1]), -sum(kv[1]), kv[0])):
        out.append(f"| **{fid}** | {len(minutes)} | {sum(minutes):.1f} |")
    diffs = notes.get("reference_diffs", [])
    if diffs:
        out += ["", "Against the reference solutions (harness-benchmark `golden/`, never copied into Cadence):", ""]
        out += [f"- {d['text'].rstrip('.')}. Runs: {_cite(d['run_ids'])}." for d in diffs]
    out.append("")
    return out


def load_notes(postmortems: Path, name: str) -> dict:
    path = postmortems / f"{name}.notes.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def covering(postmortems: Path) -> dict[str, list[str]]:
    """name -> the batches each committed postmortem covers (its notes' "batches", else the name)."""
    out = {}
    if not postmortems.is_dir():
        return out
    for path in sorted(postmortems.glob("*.md")):
        notes = load_notes(postmortems, path.stem)
        batches = notes.get("batches") or [path.stem]
        out[path.stem] = list(batches)
    return out


def render(name: str, batches: list[str], runs: Path, postmortems: Path, findings_path: Path = findings.FINDINGS,
           citations: dict | None = None) -> str:
    """The text of postmortem `name` from its notes: one batch under its own name, or several under `name`."""
    notes = load_notes(postmortems, name)
    return generate(batches if len(batches) > 1 else batches[0], runs, notes, findings_path,
                    title=name if len(batches) > 1 else None, citations=citations)


def write(name: str, batches: list[str], runs: Path, postmortems: Path, findings_path: Path = findings.FINDINGS,
          citations: dict | None = None) -> Path:
    postmortems.mkdir(parents=True, exist_ok=True)
    path = postmortems / f"{name}.md"
    path.write_text(render(name, batches, runs, postmortems, findings_path, citations), encoding="utf-8")
    return path


def refresh(batch: str, runs: Path, postmortems: Path, findings_path: Path = findings.FINDINGS,
            citations: dict | None = None) -> list[Path]:
    """After a run of `batch` is recorded: every committed postmortem that covers the batch, written again;
    `<batch>.md` written when none covers it."""
    names = [n for n, bs in covering(postmortems).items() if batch in bs] or [batch]
    return [write(n, covering(postmortems).get(n) or [batch], runs, postmortems, findings_path, citations) for n in names]


def regenerate_all(runs: Path, postmortems: Path, findings_path: Path = findings.FINDINGS,
                   citations: dict | None = None) -> list[Path]:
    return [write(n, bs, runs, postmortems, findings_path, citations) for n, bs in covering(postmortems).items()]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m loop.postmortem", description=__doc__.split("\n\n")[0])
    ap.add_argument("batch", nargs="*", help="one batch, or several for one postmortem (with --name)")
    ap.add_argument("--run", help="print the Trace row of this run instead of writing a batch postmortem")
    ap.add_argument("--all", action="store_true", help="write every committed postmortem again from its notes")
    ap.add_argument("--postmortems", type=Path, default=POSTMORTEMS, help="the postmortems folder (--all)")
    ap.add_argument("--name", help="the postmortem's name when it covers several batches")
    ap.add_argument("--runs", type=Path, default=ROOT / "runs")
    ap.add_argument("--notes", type=Path)
    ap.add_argument("--out", type=Path)
    args = ap.parse_args(argv)
    if args.run:
        try:
            print(trace.table(trace.rows(args.runs, findings.FINDINGS, trace.load_citations(), [args.run])))
        except trace.TraceError as exc:
            print(f"refused: {exc}", file=sys.stderr)
            return 2
        return 0
    if args.all:
        for path in regenerate_all(args.runs, args.postmortems):
            print(path)
        return 0
    if not args.batch:
        ap.error("a batch, --all, or --run <run id>")
    name = args.name or args.batch[0]
    if len(args.batch) > 1 and not args.name:
        ap.error("several batches need --name")
    notes_path = args.notes or ROOT / "postmortems" / f"{name}.notes.json"
    notes = json.loads(notes_path.read_text(encoding="utf-8")) if notes_path.exists() else {}
    try:
        text = generate(args.batch if len(args.batch) > 1 else args.batch[0], args.runs, notes,
                        title=args.name)
    except PostmortemError as exc:
        print(f"refused: {exc}", file=sys.stderr)
        return 2
    out = args.out or ROOT / "postmortems" / f"{name}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
